import assert from 'node:assert/strict';
import { parsePages, reconstructLines } from '../网站资源/脚本/pdf_import.js';
import '../网站资源/脚本/cost_analysis.js';

const T=globalThis.TripTime;
const bill=lines=>[{page:1,lines}];
assert.throws(()=>parsePages(bill([])),/扫描件/);
assert.throws(()=>parsePages(bill(['共2笔行程:合计4.00元','1 A B 2.00 2026-10-01 08:30:00'])),/核对不一致/);
assert.throws(()=>parsePages(bill(['共1笔行程:合计4.00元','1 A B 2.00 2026-10-01 08:30:00'])),/核对不一致/);
assert.throws(()=>parsePages(bill(['共1笔行程:合计2.00元','1 A B 2.00 2026-02-30 08:30:00'])),/不合法/);
assert.throws(()=>parsePages(bill(['共1笔行程:合计2.00元','1 A B 2.00'])),/缺少交易时间/);
assert.throws(()=>parsePages(bill(['共1笔行程:合计2.00元','2 A B 2.00 2026-10-01 08:30:00'])),/序号不连续/);
const split=parsePages([{page:1,lines:['共1笔行程:合计2.00元','1 -- 00 2.00']},{page:2,lines:['2026-10-01 08:30:00']}]);
assert.deepEqual([split.rows[0].from,split.rows[0].to],['有轨电车','有轨电车']);
const item=(str,x,y,width)=>({str,transform:[1,0,0,1,x,y],width});
assert.deepEqual(reconstructLines([item('⻰安',10,20,20),item('⻰安',10.5,20,20),item('成都西站',60,20,40)]),['龙安 成都西站']);
const trips=T.parse('出发站,到达站,时间\nA,B,2026.10.01 08:29:59\nA,B,2026.10.01 08:30:00\nA,B,2026.10.01 09:00:00\nA,B,2026.10.01 23:10:00\nA,B,2026.10.02 01:05:00').trips;
assert.equal(T.aggregate(trips,{startTime:'08:30',endTime:'09:00'}).filtered.length,1);
assert.equal(T.aggregate(trips,{startTime:'23:00',endTime:'02:00'}).filtered.length,2);
assert.equal(T.aggregate(trips,{start:'2026-10-01',end:'2026-10-01',startTime:'23:00',endTime:'02:00'}).filtered.length,1);
assert.equal(T.aggregate(trips,{startTime:'08:30',endTime:'08:30'}).filtered.length,0);
assert.equal(T.aggregate(trips,{}).filtered.length,5);
console.log('PASS: PDF validation, pagination, tram, repeated glyphs and minute filters.');
const priced=T.parse('出发站,到达站,时间,金额(元)\nA,B,2026.10.01 08:30:00,2.70\nA,B,2026.10.01 12:30:00,0\nA,B,2026.10.01 15:30:00,abc\nA,B,2026.10.01 20:30:00,');
const costs=globalThis.TripCosts.compute(priced.trips);
assert.equal(costs.total,270);assert.equal(costs.known.length,2);assert.equal(costs.missing,2);assert.equal(priced.amountErrors.length,1);
const enriched=T.parse('出发站,到达站,时间,金额\nA,B,2026.10.01 08:30:00,\nA,B,2026.10.01 08:30:00,2.70');
assert.equal(T.aggregate(enriched.trips,{dedup:true}).filtered[0].amountCents,270);
const conflict=T.parse('出发站,到达站,时间,金额\nA,B,2026.10.01 08:30:00,1\nA,B,2026.10.01 08:30:00,2');
assert.equal(conflict.trips[0].amountCents,null);assert.equal(conflict.amountErrors.length,1);
assert.equal(T.parse('出发站,到达站,时间\nA,B,2026.10.01 08:30:00').trips[0].amountCents,null);
console.log('PASS: old CSV, zero fare, partial amounts, invalid fares and duplicate fare conflicts.');
